const catalogs = { uk, en } as const;

export function t(
  key: TranslationKey,
  values: Record<string, string | number> = {},
  locale: Locale = activeLocale,
): string {
  const message = locale === "uk" ? catalogs.uk[key] : (catalogs.en[key] ?? key);
  return message.replace(/\{(\w+)\}/g, (match, name: string) =>
    Object.hasOwn(values, name) ? String(values[name]) : match,
  );
}

/** Translates known display labels while leaving API and permission identifiers untouched. */
export function translateLabel(value: string, locale: Locale = activeLocale): string {
  const source = value.trim().replace(/[._-]+/g, " ");
  const key = (Object.keys(uk) as TranslationKey[]).find(
    (candidate) => candidate.toLocaleLowerCase() === source.toLocaleLowerCase(),
  );
  return key ? t(key, {}, locale) : value;
}

/** Maps known server/auth messages and otherwise uses the caller's localized fallback. */
export function localizeError(
  error: unknown,
  fallback: string,
  locale: Locale = activeLocale,
): string {
  const message = error instanceof Error ? error.message : "";
  return Object.hasOwn(uk, message) ? t(message as TranslationKey, {}, locale) : fallback;
}

export function leadCountLabel(count: number, locale: Locale = activeLocale): string {
  if (locale === "en") return `${count} ${count === 1 ? "lead" : "leads"}`;
  const lastTwo = count % 100;
  const last = count % 10;
  if (lastTwo >= 11 && lastTwo <= 14) return `${count} лідів`;
  if (last === 1) return `${count} лід`;
  if (last >= 2 && last <= 4) return `${count} ліди`;
  return `${count} лідів`;
}
